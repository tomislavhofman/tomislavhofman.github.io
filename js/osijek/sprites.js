// Toon shading like the 3D scene: the fur pixel next to the outline on the shaded side
// (right in the front view, bottom in the side view) gets the darker band.
function shade(rows, side) {
  const out = rows.map((r) => [...r]);
  if (side === 'right') {
    out.forEach((r) => {
      for (let x = r.length - 1; x > 0; x--) {
        if (r[x] === 'o' && (r[x - 1] === 'g' || r[x - 1] === 'w')) { r[x - 1] = 's'; if (r[x - 2] === 'g') r[x - 2] = 's'; break; }
      }
    });
  } else {
    for (let x = 0; x < out[0].length; x++) {
      for (let y = out.length - 1; y > 0; y--) {
        if (out[y][x] === 'o' && (out[y - 1][x] === 'g' || out[y - 1][x] === 'w')) { out[y - 1][x] = 's'; break; }
      }
    }
  }
  return out.map((r) => r.join(''));
}

const mirror = (halves) => halves.map((r) => r + [...r].reverse().join(''));
const pad = (rows, left, right) => rows.map((r) => '.'.repeat(left) + r + '.'.repeat(right));
const put = (rows, row, col, text) => rows.map((r, i) => (i === row ? r.slice(0, col) + text + r.slice(col + text.length) : r));

